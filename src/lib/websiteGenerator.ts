function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (char) => {
    switch (char) {
      case "&": return "&amp;";
      case "<": return "&lt;";
      case ">": return "&gt;";
      case '"': return "&quot;";
      default: return "&#39;";
    }
  });
}

function slugify(value: string): string {
  const slug = value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return slug || "website";
}

function cleanName(raw: string | undefined): string {
  if (!raw) return "";
  let name = raw.replace(/^["']|["']$/g, "").trim();
  let previous = "";
  while (name && name !== previous) {
    previous = name;
    name = name.replace(/\b(website|web site|site|web app|app|page|please|thanks|with|using|that|and)\s*$/i, "").trim();
  }
  if (name.length > 40) name = name.slice(0, 40).trim();
  if (/^(me|a|an|the|my|full|stack|fullstack)$/i.test(name)) return "";
  return name;
}

function detectKind(text: string): WebsiteKind {
  const lower = text.toLowerCase();
  if (/\b(store|shop|e-?commerce)\b/.test(lower)) return "store";
  if (/\b(dashboard|admin)\b/.test(lower)) return "dashboard";
  if (/\bblog\b/.test(lower)) return "blog";
  if (/\bportfolio\b/.test(lower)) return "portfolio";
  return "landing";
}

/**
 * Detect a request to scaffold a website. Ordinary coding questions stay with the chat model.
 */
export function parseWebsiteRequest(text: string): WebsiteBrief | null {
  const raw = text.trim();
  if (!raw) return null;

  const direct = /\b(?:build|create|generate|make|scaffold)\s+(?:me\s+)?(?:(?:a|an|the)\s+)?(?:full[-\s]?stack\s+)?(?:landing(?:\s+page)?|portfolio|blog|dashboard|admin|store|shop|e-?commerce)?\s*(?:web\s*)?(?:site|website|page)\b/i;
  const fullStackBuild = /\b(?:build|create|generate|make|scaffold)\b[\s\S]{0,48}\bfull[-\s]?stack\b/i;
  const shortCommand = /^\s*(?:open|run|use|start)?\s*website generator\s*\.?\s*$/i;

  if (!direct.test(raw) && !fullStackBuild.test(raw) && !shortCommand.test(raw)) return null;

  const nameMatch = raw.match(/\b(?:called|named|titled|for)\s+["']?([A-Za-z0-9][^"\n]{0,48})/i);
  const name = cleanName(nameMatch?.[1]) || "Lunor Studio";
  return { kind: detectKind(raw), name };
}

