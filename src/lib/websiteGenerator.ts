const BUILDERS: Record<WebsiteKind, (name: string) => { files: GeneratedFile[]; routes: string[] }> = {
  landing,
  portfolio,
  blog,
  store,
  dashboard,
};

export function generateWebsite(kind: WebsiteKind, siteName: string): GeneratedWebsite {
  const builder = BUILDERS[kind];
  if (!builder) {
    throw new Error(`Unknown website automation: ${kind}`);
  }
  const name = siteName.trim() || "Lunor Site";
  const slug = slugifySiteName(name);
  const built = builder(name);
  const files: GeneratedFile[] = [
    ...built.files,
    {
      path: "server/package.json",
      language: "json",
      content: packageJson(slug, `${name} ${KIND_LABEL[kind].toLowerCase()}`),
    },
    {
      path: "README.md",
      language: "markdown",
      content: readme(name, kind, built.routes),
    },
  ];
  const fileList = files.map((file) => `\`${file.path}\``).join(", ");
  const summary = `**${KIND_LABEL[kind]} generated for ${name}.**\n\nFiles written: ${fileList}.\n\nThe preview runs \`client/index.html\` on its own. To start the API:\n\n\`\`\`bash\ncd server && npm install && npm start\n\`\`\`\n\nRoutes: ${built.routes.map((route) => `\`${route}\``).join(", ")}.`;

  return { kind, label: KIND_LABEL[kind], name, slug, files, summary };
}
