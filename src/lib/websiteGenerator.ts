export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export function slugifySiteName(value: string): string {
  const slug = value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);
  return slug || "lunor-site";
}

export function isNodeServerSource(source: string): boolean {
  return /lunor-node-server|\brequire\s*\(|\bmodule\.exports\b|from\s+["']express["']|createServer\s*\(/.test(source);
}

export function filesToProjectTree(files: GeneratedFile[]): ProjectFileNode[] {
  const root: ProjectFileNode[] = [];

  for (const file of files) {
    const parts = file.path.split("/").filter(Boolean);
    let level = root;
    let acc = "";
    parts.forEach((part, index) => {
      acc = acc ? `${acc}/${part}` : part;
      const isFile = index === parts.length - 1;
      if (isFile) {
        const existing = level.find((node) => node.id === acc && node.type === "file");
        if (existing) {
          existing.content = file.content;
          existing.language = file.language;
          return;
        }
        level.push({
          id: acc,
          name: part,
          type: "file",
          language: file.language,
          content: file.content,
        });
        return;
      }
      let folder = level.find((node) => node.id === acc && node.type === "folder");
      if (!folder) {
        folder = { id: acc, name: part, type: "folder", isOpen: true, children: [] };
        level.push(folder);
      }
      folder.children = folder.children || [];
      level = folder.children;
    });
  }

  return root;
}

