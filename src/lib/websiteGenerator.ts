export function websiteFilesToTree(files: GeneratedFile[]): WebsiteTreeNode[] {
  const root: WebsiteTreeNode[] = [];

  const ensureFolder = (nodes: WebsiteTreeNode[], id: string, name: string): WebsiteTreeNode => {
    let folder = nodes.find((node) => node.id === id && node.type === "folder");
    if (!folder) {
      folder = { id, name, type: "folder", isOpen: true, children: [] };
      nodes.push(folder);
    }
    return folder;
  };

  for (const file of files) {
    const parts = file.path.split("/").filter(Boolean);
    let nodes = root;
    let acc = "";
    parts.forEach((part, index) => {
      acc = acc ? `${acc}/${part}` : part;
      if (index === parts.length - 1) {
        const existing = nodes.find((node) => node.id === acc);
        const leaf: WebsiteTreeNode = {
          id: acc,
          name: part,
          type: "file",
          language: file.language,
          content: file.content,
        };
        if (existing) Object.assign(existing, leaf);
        else nodes.push(leaf);
      } else {
        nodes = ensureFolder(nodes, acc, part).children || [];
      }
    });
  }

  return root;
}
