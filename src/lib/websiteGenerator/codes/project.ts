import type { WebsiteBrief } from "../types";

export function buildPackageJson(brief: WebsiteBrief): string {
  return JSON.stringify(
    {
      name: brief.slug,
      private: true,
      version: "1.0.0",
      type: "module",
      description: brief.summary,
      scripts: {
        start: "node server/server.cjs",
      },
    },
    null,
    2,
  ) + "\n";
}

export function buildEnvExample(): string {
  return `PORT=3000
`;
}

export function buildReadme(brief: WebsiteBrief): string {
  return `# ${brief.name}

${brief.summary}

This project was generated by the Lunor web development website generator.

## What you get

- \`src/index.html\`, \`src/style.css\`, \`src/app.js\` — the website the editor preview renders
- \`server/server.cjs\` — a Node HTTP server with no npm dependencies

## Run it

\`\`\`bash
npm start
\`\`\`

Open http://localhost:3000. The page works in the editor preview without the server. The contact form reaches \`POST /api/contact\` after \`npm start\`.
`;
}
